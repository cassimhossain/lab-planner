#!/usr/bin/env python3
"""Pull the text out of every presentation in library/slides/ and write
buddy/slides.js, which Study Buddy searches so its answers match how the
club teaches (and can say "this is on slide 5 of JM-03").

Run it after adding or changing presentations, from the lab-planner folder:
    python3 tools/build_slide_text.py

It uses macOS's own PDF reader (PDFKit, through osascript), so it needs a Mac
and nothing to install.
"""
import json, os, re, subprocess, sys

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SLIDES = os.path.join(HERE, "library", "slides")
OUT = os.path.join(HERE, "buddy", "slides.js")

JXA = r'''
ObjC.import("Quartz");
function run(argv) {
  var d = $.PDFDocument.alloc.initWithURL($.NSURL.fileURLWithPath(argv[0]));
  if (!d) return "[]";
  var pages = [];
  for (var i = 0; i < d.pageCount; i++) { var s = d.pageAtIndex(i).string; pages.push(s ? s.js : ""); }
  return JSON.stringify(pages);
}
'''
FOOTER = re.compile(r"Robotics & AI Club · .*?Curriculum by Qasim Mushtaq|^\s*\d+\s*/\s*\d+\s*$", re.M)


def clean(text, code):
    text = FOOTER.sub(" ", text)
    text = re.sub(r"^\s*" + re.escape(code) + r"\s*·\s*", "", text)   # the deck's own header line
    text = re.sub(r"[ \t]+", " ", text)
    text = re.sub(r"\s*\n\s*", " · ", text.strip())
    return re.sub(r"( · )+", " · ", text).strip(" ·")[:900]


def main():
    if sys.platform != "darwin":
        sys.exit("This tool uses macOS's PDF reader; run it on a Mac.")
    decks = []
    for name in sorted(os.listdir(SLIDES)):
        if not name.endswith(".pdf"):
            continue
        code = name.split("_")[0]
        out = subprocess.run(["osascript", "-l", "JavaScript", "-e", JXA, os.path.join(SLIDES, name)], capture_output=True, text=True)
        try:
            pages = json.loads(out.stdout.strip() or "[]")
        except json.JSONDecodeError:
            print("  could not read", name); continue
        title = re.sub(r"_Slides$", "", name[len(code) + 1:-4]).replace("_", " ")
        decks.append({"c": code, "t": title, "p": [clean(p, code) for p in pages]})
        print(f"  {code}: {len(pages)} slides")
    body = json.dumps(decks, ensure_ascii=False, separators=(",", ":"))
    with open(OUT, "w", encoding="utf-8") as f:
        f.write("/* Generated by tools/build_slide_text.py from library/slides. Don't edit by hand:\n"
                "   change the presentation and run the tool again. */\n")
        f.write("window.BUDDY_SLIDES = " + body + ";\n")
    print(f"{len(decks)} decks -> buddy/slides.js ({os.path.getsize(OUT) // 1024} KB)")


if __name__ == "__main__":
    main()
